"""Failure-report rendering.

The report is the product. A check run that ends in a shrug changes
nothing; a report that names the failure, locates it, and states the rule
it violates becomes part of how the producing system is graded. Reports
render as terminal text, Markdown (for files, issues, and PRs), or JSON
(for machines).
"""

from __future__ import annotations

import json
from datetime import datetime, timezone

from .models import CheckResult

#: Why each check exists, in one line — printed in every report so a reader
#: who has never seen the tool understands what the failure costs.
WHY_IT_MATTERS = {
    "FL001": "A placeholder that ships is indistinguishable from finished work until a human reads it — by then it is public.",
    "FL002": "A claim without evidence is the producing system grading its own homework; downstream steps build on it as if it were fact.",
    "FL003": "Correct work on stale state is wrong work with extra confidence — the plan is flawless for a world that no longer exists.",
    "FL004": "The claimed number is what travels into dashboards and decisions; the itemized record is the only part that was ever true.",
    "FL005": "Existence is not completeness: a deliverable can pass every outline check while a component inside it is silently absent.",
}

_STATUS_MARK = {"pass": "PASS", "warn": "WARN", "fail": "FAIL"}


def _verdict_line(result: CheckResult) -> str:
    return (
        f"Verdict: {result.verdict} "
        f"({len(result.errors)} error(s), {len(result.warnings)} warning(s))"
    )


def render_text(result: CheckResult, source: str = "<document>") -> str:
    """Plain-text report for terminals and logs."""
    lines = [
        "FAILLOUD — agent output verification",
        f"Source: {source}",
        _verdict_line(result),
        "",
    ]
    for outcome in result.outcomes:
        lines.append(
            f"[{outcome.check_id}] {outcome.name} — {_STATUS_MARK[outcome.status]}"
        )
        for finding in outcome.findings:
            mark = "✗" if finding.severity.value == "error" else "!"
            lines.append(f"  {mark} {finding.path} — {finding.message}")
    if not result.findings:
        lines.append("No silent failures found. The output backs its claims.")
    return "\n".join(lines) + "\n"


def render_markdown(result: CheckResult, source: str = "<document>") -> str:
    """The formal FAILURE REPORT, suitable to attach to a run, an issue,
    or a pull request."""
    generated = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    lines = [
        "# FAILURE REPORT" if not result.passed else "# VERIFICATION REPORT",
        "",
        f"**Source:** `{source}`  ",
        f"**Generated:** {generated}  ",
        f"**Verdict:** **{result.verdict}** — "
        f"{len(result.errors)} error(s), {len(result.warnings)} warning(s)",
        "",
        "## Checks",
        "",
        "| Check | Name | Result | Findings |",
        "|---|---|---|---|",
    ]
    for outcome in result.outcomes:
        lines.append(
            f"| {outcome.check_id} | {outcome.name} | "
            f"{_STATUS_MARK[outcome.status]} | {len(outcome.findings)} |"
        )
    lines += ["", "## Findings", ""]
    if not result.findings:
        lines.append("No silent failures found. Every claim in this output is backed by its own record.")
        lines.append("")
    for outcome in result.outcomes:
        if not outcome.findings:
            continue
        lines.append(f"### {outcome.check_id} — {outcome.name}")
        lines.append("")
        lines.append(f"*Why it matters: {WHY_IT_MATTERS.get(outcome.check_id, '')}*")
        lines.append("")
        for finding in outcome.findings:
            lines.append(
                f"- **{finding.severity.value.upper()}** `{finding.path}` — {finding.message}"
            )
        lines.append("")
    lines += [
        "---",
        "Generated by FailLoud. A FAIL means the output should not be trusted "
        "or shipped downstream until the findings are resolved — or the "
        "producing agent re-runs and its new output passes.",
        "",
    ]
    return "\n".join(lines)


def render_json(result: CheckResult, source: str = "<document>") -> str:
    """Machine-readable report for CI and pipelines."""
    payload = result.to_dict()
    payload["source"] = source
    payload["tool"] = "failloud"
    return json.dumps(payload, indent=2) + "\n"
